export type MetricKey = keyof typeof tokens.metric

/** Media query for the reduced-motion preference (WCAG 2.3.3): no springs or slides, short cross-fades instead. */
export const REDUCED_MOTION_QUERY = '(prefers-reduced-motion: reduce)'

/** Reduced transparency: a translucent surface turns opaque rather than blurring (`chromeSurface`/`sheetSurface`). */
export const REDUCED_TRANSPARENCY_QUERY = '(prefers-reduced-transparency: reduce)'

/** More contrast: a translucent surface turns opaque and gains a defined border. */
export const MORE_CONTRAST_QUERY = '(prefers-contrast: more)'

/** True when the viewer asked for reduced motion. Safe outside a browser (false). */
export function prefersReducedMotion(): boolean {
  return typeof window !== 'undefined' && typeof window.matchMedia === 'function' && window.matchMedia(REDUCED_MOTION_QUERY).matches
}

/** Scroll behaviour that honours the reduced-motion preference. */
export function scrollBehavior(): ScrollBehavior {
  return prefersReducedMotion() ? 'auto' : 'smooth'
}

/** Hex colour with alpha (0–1), e.g. the 12 % forecast band. */
export function withAlpha(hex: string, alpha: number): string {
  const a = Math.round(Math.min(1, Math.max(0, alpha)) * 255)
    .toString(16)
    .padStart(2, '0')
  return `${hex}${a}`
}

/** The CSS gradient for a metric card, left to right. */
export function metricGradient(metric: MetricKey): string {
  const [from, to] = tokens.gradient[metric]
  return `linear-gradient(135deg, ${from} 0%, ${to} 100%)`
}

/**
 * True when the browser can animate with a `linear()` easing curve (Safari 17.2+, Chrome 113+). The probe itself
 * happened once, when `SPRING` was built at module load, so this is only a read.
 */
export function supportsSpring(): boolean {
  return SPRING !== null
}

/**
 * The easing an entrance settles with: a real critically damped spring where the browser takes `linear()`, and the
 * equivalent strong-decelerate cubic-bézier where it doesn't. `easing.exit` is the exact mirror of the fallback, so
 * a reversible transition still retraces its path either way.
 */
export function enterEasing(): string {
  return SPRING ?? tokens.motion.easing.enter
}

/**
 * How long an entrance takes: the settle time the spring derives from its own parameters, never a number chosen for
 * it. Always pair this with `enterEasing()` — a spring curve given less time than it needs is cut off mid-settle, and
 * one given more sits motionless at the end of its travel while the user waits for it.
 */
export function enterDuration(): number {
  return ENTER_DURATION
}

/**
 * The entrance to play when the viewer prefers reduced motion: a short cross-fade and no travel at all, where a
 * spring would have risen and settled. Returns `animation`'s shorthand value, so a caller can pass it straight through
 * either way — `'none'` when motion is not reduced. Takes `reduced` rather than reading the media query itself so a
 * caller's `useMediaQuery` is what drives a re-render when the preference changes.
 */
export function reducedEntrance(delay: number, reduced: boolean): string {
  if (!reduced) return 'none'
  return `${tokens.motion.duration.fast}ms ${tokens.motion.easing.standard} ${delay}ms both crossFadeIn`
}

/**
 * The properties that still aid comprehension when motion is reduced, so they keep a short cross-fade instead of
 * losing their transition: colour, opacity and elevation carry meaning on their own. Travel and scale (`transform`,
 * `width`) are the opposite — they are exactly what a motion-sensitive viewer asked to be spared.
 */
const REDUCED_MOTION_SURVIVORS = /^(opacity|color|background-color|border-color|outline-color|box-shadow|fill|stroke)$/

/**
 * A transition string for the given properties. Every hand-written transition in the app goes through this, so the
 * reduced-motion preference cannot be forgotten in one place (WCAG 2.3.3).
 *
 * Reduced motion means a *gentler equivalent*, not the absence of one: the HIG asks for cross-fades in place of
 * slides and springs. So under the preference this keeps the changes that still help — a colour, an opacity, a shadow —
 * at the instant step, and drops only the movement. (It previously returned `none` for everything, which quietly
 * deleted the cross-fades the app had promised to keep.)
 *
 * Note that MUI's CssBaseline squashes *every* transition duration to 0.01 ms under this same preference, so in the
 * running app those survivors arrive instantly rather than over `instant`. That is left as it is, deliberately: what
 * remains after the movement is dropped is a colour or an opacity, which reads correctly as an immediate change, and
 * relaxing the blanket rule would put MUI's own drawer and popover travel back on screen. The policy is still stated
 * here, so it survives a change to the baseline underneath it.
 */
export function transitionOf(
  properties: string | readonly string[],
  duration: number = tokens.motion.duration.base,
  easing: string = tokens.motion.easing.standard,
): string {
  const list = typeof properties === 'string' ? [properties] : properties
  if (prefersReducedMotion()) {
    const kept = list
      .map((p) => p.trim())
      .filter((p) => REDUCED_MOTION_SURVIVORS.test(p))
      .map((p) => `${p} ${tokens.motion.duration.instant}ms ${tokens.motion.easing.standard}`)
    return kept.join(', ') || 'none'
  }
  return list.map((p) => `${p} ${duration}ms ${easing}`).join(', ')
}

