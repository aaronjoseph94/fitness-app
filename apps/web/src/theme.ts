// Owns: every visual token (SPEC §11) — ink, metric palette, semantic status colours, the type scale, spacing,
// radius hierarchy, materials, elevation, motion, chart style, muscle-map steps — and the MUI theme built from them.
// Nothing else in the app hard-codes a colour. Charts read `tokens` directly so SVG output carries literal hex
// colours for print and the PDF archive.
//
// Visual language (2026-10-06, "Apple HIG rebuild" — see docs/APPLE-DESIGN.md for the audit and the full decision
// log): the canvas is the platform's grouped grey, cards are white 16 px surfaces separated by surface contrast
// rather than by an outline, and the chrome (top bar, tabs, rail) is a translucent material content scrolls under.
// Type is the platform's own face — which ships optical sizing, tracking tables and legibility tuning — on a nine-step
// scale where tracking is size-specific and leading tracks size inversely. Motion is expressed Apple's way, as a
// *response* with a critically damped spring (`linear()` where the browser has it, the equivalent cubic-bézier
// otherwise — both generated by the solver in `motion/spring.ts`, so a curve and the duration it is given can never
// drift apart), and exit is the exact mirror of enter so a dismissal retraces its arrival. Bounce is spent only where
// a gesture carried momentum into the release, which is the one place an overshoot is earned; reduced motion keeps
// its cross-fades rather than losing them (see `transitionOf`).
//
// Colour (2026-10-06): the action colour is Facebook blue (#166FE5 — Meta's own blue, one step down from the
// #1877F2 brand fill so white text on a button measures 4.73:1 and clears AA; the brand fill itself is only 4.23:1).
// Values are unchanged by the rebuild — the change is restraint in *use*: chrome is neutral, and colour is spent on
// data and on the primary action. Every pair below was measured, not eyeballed: white on a metric gradient passes
// WCAG AA 4.5:1 at BOTH stops, and every metric colour clears 3:1 against both the card and the page.
